import fs from "node:fs";
const read = p => JSON.parse(fs.readFileSync(new URL("../" + p, import.meta.url), "utf8"));
const forms=read("catalogo/formacoes.json").formacoes;
const cases=read("catalogo/cases.json").cases;
const f01=read("formacoes/F01-arquitectura-superinteligencia-agentica/aulas.json");
const f02=read("formacoes/F02-genesis/ateliers.json");
const offer=read("ofertas/hotmart.json");
const assert=(x,msg)=>{ if(!x) throw new Error(msg); };
assert(forms.length===2 && forms[0].id==="F01" && forms[1].id==="F02","Catálogo F01/F02 inválido");
assert(forms[0].titulo==="A Arquitectura da SuperInteligência Agêntica","Nome oficial da F01 não corresponde");
assert(cases.length===6 && new Set(cases.map(c=>c.id)).size===6,"Case Library inválida");
assert(cases.every(c=>c.origem_formacao==="F01"),"Origem dos Cases inválida");
assert(f01.formacao==="F01" && f01.aulas.length===3,"F01 exige três lives");
assert(f01.aulas.map(a=>a.data).join(",")==="2026-11-09,2026-11-12,2026-11-19","Datas F01 não correspondem à decisão");
assert(f01.aulas.every(a=>a.duracao_min===90),"Duração F01 inválida");
assert(f02.formacao==="F02" && f02.ateliers.length===24,"Genesis exige 24 ateliers");
assert(f02.ateliers.every((a,i)=>a.semana===Math.floor(i/3)+1),"Semanas Genesis inválidas");
assert(f02.ateliers_preparatorios_adicionais.length===3,"Genesis precisa de três preparatórios adicionais");
assert(f02.contagem_total_eventos_previstos===27,"Contagem de ateliers Genesis inválida");
assert(f02.ateliers_preparatorios_adicionais.filter(a=>a.mes==="2026-11").length===1,"Um atelier em novembro");
assert(f02.ateliers_preparatorios_adicionais.filter(a=>a.mes==="2026-12").length===2,"Dois ateliers em dezembro");
assert(offer.produtos[0].preco_brl===147 && offer.produtos[1].preco_brl===490 && offer.produtos[1].estudante.preco_brl===190,"Preços não correspondem à decisão");
assert(offer.produtos[1].acesso_F01_lives_incluido===true,"Genesis deve incluir lives F01");
assert(f01.aulas.every(a=>!a.publicado_clubos) && f02.ateliers.every(a=>!a.publicado_clubos),"Publicação não homologada");
console.log("PASS F01 R$147 09/12/19; Genesis R$490/R$190 3+24; Case Library 6/6");
